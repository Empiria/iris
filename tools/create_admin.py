#!/usr/bin/env -S uv run --script
# /// script
# requires-python = ">=3.10"
# dependencies = ["anvil-uplink>=0.7.1"]
# ///
"""Local launcher for scripts/CreateAdmin.py, the first-admin script (DEPL-03).

Local only: it connects to the dev stack over the dev uplink and launches the
script as a background task. A hosted deployment runs the script from the Anvil
editor instead (see the docstring in scripts/CreateAdmin.py), and this launcher
never takes an uplink key or URL for one: any URL that is not ws:// on localhost
or 127.0.0.1 is refused.

`--dev` ensures the two local dev accounts (an admin user and a non-admin viewer)
that `just seed` and the e2e tests sign in with. Without it the email is an
argument and the password comes from IRIS_ADMIN_PASSWORD, or is generated by the
script and read from `just logs`. No option takes a secret on the command line.

The password reaches the script as a launch argument and is never printed here.
Launch arguments can appear in the local app-server log; that is accepted for the
loopback dev stack.
"""

import argparse
import contextlib
import os
import sys
import threading
import time
from pathlib import Path
from urllib.parse import urlparse

# A sibling in tools/. Put tools/ on the path so a load by file path finds it too.
sys.path.insert(0, str(Path(__file__).resolve().parent))
import stack_url  # noqa: E402

# Local-stack-only values. They match the Containerfile and tools/dev_seed.py and
# protect nothing: the stack is bound to loopback. The URL is not here: the stack's
# host port is random, so stack_url.py finds it.
LOCAL_KEY = "dev-uplink"
DEV_ADMIN_EMAIL = "admin@example.test"
DEV_ADMIN_PASSWORD = "dev-admin-password-local"
DEV_VIEWER_EMAIL = "viewer@example.test"
DEV_VIEWER_PASSWORD = "dev-viewer-password-local"

SCRIPT_NAME = "script:CreateAdmin"
LOCAL_HOSTS = ("localhost", "127.0.0.1")

# How long to wait for the uplink to come up, and for the script to finish.
CONNECT_TIMEOUT_S = 20
SCRIPT_TIMEOUT_S = 60
POLL_S = 0.5


class ScriptFailed(Exception):
    """The script ended in failure. The message is the script's own error text."""


def resolve_connection(environ, url_file=None):
    """The (url, key) to connect with. Refuses anything but a local ws URL.

    The URL is IRIS_UPLINK_URL, else derived from IRIS_URL or `.anvil/stack-url`
    (see stack_url.py). With none of those it raises stack_url.NoStack, a
    ValueError whose message says how to start a stack.
    """
    url = stack_url.uplink_url(environ, url_file)
    key = environ.get("IRIS_UPLINK_KEY") or LOCAL_KEY
    parts = urlparse(url)
    if parts.scheme != "ws" or parts.hostname not in LOCAL_HOSTS:
        # Say nothing about the URL or the key: either could carry a credential.
        raise ValueError(
            "this launcher only talks to the local dev stack (ws://localhost). "
            "A hosted deployment runs CreateAdmin from the Anvil editor: see "
            "the docstring in scripts/CreateAdmin.py."
        )
    return url, key


def _hide(text, password):
    text = str(text)
    return text.replace(password, "[hidden]") if password else text


def launch_script(
    server, email, password, timeout, sleep=time.sleep, clock=time.monotonic
):
    """Launch the script and wait. Returns ("created", None) or ("failed", text)."""
    launch_args = (email,) if password is None else (email, password)
    task = server.launch_background_task(SCRIPT_NAME, *launch_args)
    deadline = clock() + timeout
    while True:
        status = task.get_termination_status()
        if status is not None:
            break
        if clock() >= deadline:
            raise TimeoutError(f"CreateAdmin did not finish within {timeout} seconds")
        sleep(POLL_S)
    if status == "completed":
        return "created", None
    try:
        error = task.get_error()
    except Exception as exc:
        # The uplink's get_error re-raises the task's exception, not returns it.
        error = exc
    return "failed", _hide(error, password)


def _is_admin(tables, email):
    row = tables.users.get(email=email)
    return row is not None and bool(row["is_admin"])


def ensure_admin(
    email, password, server, tables, timeout=SCRIPT_TIMEOUT_S, sleep=time.sleep
):
    """Make sure the admin account exists. Returns "present" or "created"."""
    if _is_admin(tables, email):
        return "present"
    status, error = launch_script(server, email, password, timeout, sleep=sleep)
    if status != "created":
        raise ScriptFailed(error)
    return "created"


def ensure_viewer(email, password, users_api, tables):
    """Make sure a non-admin account exists. Returns "present" or "created"."""
    if tables.users.get(email=email) is not None:
        return "present"
    users_api.signup_with_email(email, password)
    return "created"


def parse_args(argv, environ):
    """Returns (email, password, dev). The password is None when none is given."""
    parser = argparse.ArgumentParser(
        prog="create_admin",
        description="Create the first admin account on the local dev stack.",
    )
    parser.add_argument("email", nargs="?", help="the admin email address")
    parser.add_argument(
        "--dev",
        action="store_true",
        help="create the local dev admin and viewer accounts",
    )
    parsed = parser.parse_args(argv)
    if parsed.dev:
        return DEV_ADMIN_EMAIL, DEV_ADMIN_PASSWORD, True
    if not parsed.email:
        parser.error("an email is required unless --dev is given")
    return parsed.email, environ.get("IRIS_ADMIN_PASSWORD") or None, False


@contextlib.contextmanager
def _uplink(url, key):
    """Connect for the block, yielding (server, users, app_tables)."""
    import anvil.server

    # anvil-uplink retries a dropped connection on a non-daemon thread, which
    # keeps the process alive after the work is done. Turn that off.
    anvil.server.reconnect = lambda closed_connection: None

    def give_up():
        print(
            f"create_admin: could not reach the app server at {url}; "
            "start the stack with 'just up'",
            file=sys.stderr,
            flush=True,
        )
        os._exit(1)

    watchdog = threading.Timer(CONNECT_TIMEOUT_S, give_up)
    watchdog.daemon = True
    watchdog.start()
    try:
        anvil.server.connect(key, url=url)
    finally:
        watchdog.cancel()
    try:
        import anvil.users
        from anvil.tables import app_tables

        yield anvil.server, anvil.users, app_tables
    finally:
        anvil.server.disconnect()


def _run(email, password, dev, server, users_api, tables, sleep):
    result = ensure_admin(email, password, server, tables, sleep=sleep)
    print(f"create_admin: admin account {result} ({email})")
    if password is None:
        print("create_admin: password generated: read it in just logs")
    if dev:
        result = ensure_viewer(DEV_VIEWER_EMAIL, DEV_VIEWER_PASSWORD, users_api, tables)
        print(f"create_admin: viewer account {result} ({DEV_VIEWER_EMAIL})")


def main(argv=None, environ=None, connect=None, sleep=time.sleep):
    argv = sys.argv[1:] if argv is None else argv
    environ = os.environ if environ is None else environ
    connect = connect or _uplink
    email, password, dev = parse_args(argv, environ)
    try:
        url, key = resolve_connection(environ)
    except ValueError as exc:
        print(f"create_admin: {exc}", file=sys.stderr)
        return 1
    try:
        with connect(url, key) as (server, users_api, tables):
            _run(email, password, dev, server, users_api, tables, sleep)
    except ScriptFailed as exc:
        print(f"create_admin: CreateAdmin failed: {exc}", file=sys.stderr)
        return 1
    except (TimeoutError, OSError) as exc:
        print(f"create_admin: {_hide(exc, password)}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
